// Runtime egress session for wb-egress.yml (R5 §4.12). macOS only, run as
// root (`sudo "$(command -v bun)" scripts/wb-egress/session.ts …`).
//
// Isolation: GitHub's runner agent runs as the login user and must keep its
// own connection, so pf cannot block "all outbound" for the machine. The app
// runs as a dedicated, fresh user instead (--user, created by the workflow)
// and the pf anchor blocks and logs every outbound TCP/UDP packet of THAT
// user except loopback, DNS and the resolved IPs of the R5 §1 hosts that can
// be resolved (wildcard CDN hosts cannot; the model download is meant to hit
// a local HF mock, see TODO). The anchor is loaded under `com.apple/` so the
// stock /etc/pf.conf (`anchor "com.apple/*"`) evaluates it.
//
// Steps (what is feasible before later slices):
//   1. pf anchor + pflog0 capture + DNS capture with process metadata;
//   2. launch the release app with a fresh profile and WISPRBRO_SELFCHECK=1;
//   3. wait for `fork selfcheck: PASS|FAIL` (IPC + identity, F-05);
//   4. idle (default 120 s) – covers Handy's launch-time update check, which
//      the frontend runs when update checks are on (default);
//   5. stop, unload pf, analyse (analyze.ts), write report.json, exit 1 on
//      any violation.
//
// TODO (later slices; see the workflow header): skip onboarding (S-29a),
// 5 dictation takes from WAV fixtures (needs a fork test hook to feed audio,
// S-01/S-04), open every Hub page (S-13), a model download from a local HF
// mock on loopback (needs the fork::net / model mirror hook, F-08/S-07a).
//
// Usage:
//   session.ts --app "<path>/Wispr Bro.app" --user wbegress --out <dir>
//              [--idle 120] [--mode isolated|observe] [--strict-dns]
// `--mode observe` runs the app as the invoking user with no pf block (DNS
// capture only), for runners where a second GUI user cannot start the app.

import { spawn, spawnSync, type ChildProcess } from "node:child_process";
import { promises as dns } from "node:dns";
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
  openSync,
} from "node:fs";
import { join } from "node:path";
import { readList, REPO_ROOT, argValue } from "../wb-guard-lib";
import { analyze } from "./analyze";

const ANCHOR = "com.apple/250.WisprBroEgress";
const IDENTIFIER = "com.wisprbro.desktop";

function sh(cmd: string, args: string[], allowFail = false): string {
  const r = spawnSync(cmd, args, { encoding: "utf8" });
  if (r.status !== 0 && !allowFail) {
    throw new Error(
      `${cmd} ${args.join(" ")} failed (${r.status}): ${r.stderr}`,
    );
  }
  return `${r.stdout ?? ""}${r.stderr ?? ""}`;
}

function capture(args: string[], file: string): ChildProcess {
  const fd = openSync(file, "w");
  return spawn("tcpdump", args, { stdio: ["ignore", fd, fd] });
}

async function resolveAll(hosts: string[]): Promise<string[]> {
  const ips = new Set<string>();
  // Resolve a few times: GitHub rotates A records.
  for (let round = 0; round < 3; round++) {
    for (const h of hosts) {
      for (const fam of [dns.resolve4, dns.resolve6] as const) {
        try {
          for (const ip of await fam.call(dns, h)) ips.add(ip);
        } catch {
          // No record of that family.
        }
      }
    }
  }
  return [...ips].sort();
}

export function anchorRules(user: string, ips: string[]): string {
  const table = ips.length
    ? `table <wb_allowed> const { ${ips.join(", ")} }\n`
    : "";
  return (
    `# Wispr Bro egress anchor (generated by scripts/wb-egress/session.ts)\n` +
    table +
    `pass out quick on lo0 all\n` +
    `pass out quick proto { tcp, udp } from any to any port 53 user ${user}\n` +
    (ips.length
      ? `pass out quick proto tcp from any to <wb_allowed> port 443 user ${user}\n`
      : "") +
    `block drop out log quick proto { tcp, udp } from any to any user ${user}\n`
  );
}

async function waitFor(
  file: () => string | undefined,
  re: RegExp,
  ms: number,
): Promise<boolean> {
  const end = Date.now() + ms;
  while (Date.now() < end) {
    const p = file();
    if (p && existsSync(p) && re.test(readFileSync(p, "utf8"))) return true;
    await Bun.sleep(1000);
  }
  return false;
}

async function main() {
  const argv = process.argv.slice(2);
  const app = argValue(argv, "--app");
  const out = argValue(argv, "--out") ?? join(REPO_ROOT, "egress-out");
  const user = argValue(argv, "--user") ?? "wbegress";
  const mode = argValue(argv, "--mode") ?? "isolated";
  const idle = Number(argValue(argv, "--idle") ?? "120");
  if (!app) throw new Error("--app <path to .app> is required");
  if (process.getuid?.() !== 0) throw new Error("run as root (sudo)");
  mkdirSync(out, { recursive: true });

  const allowedEntries = readList(REPO_ROOT, "ci/allowed-hosts.txt");
  const allowed = allowedEntries
    .filter((e) => e.section === "network" || e.section === "loopback")
    .map((e) => e.value.toLowerCase());
  const resolvable = allowed.filter(
    (h) => !h.startsWith("*.") && h.includes("."),
  );

  const macos = join(app, "Contents", "MacOS");
  const exe = readdirSync(macos).map((n) => join(macos, n))[0];
  if (!exe) throw new Error(`no executable in ${macos}`);
  const exeName = exe.split("/").pop()!;
  const runAs =
    mode === "isolated" ? user : (process.env.SUDO_USER ?? "runner");
  const home = sh("dscl", [".", "-read", `/Users/${runAs}`, "NFSHomeDirectory"])
    .split(":")
    .pop()!
    .trim();
  const logFile = join(home, "Library", "Logs", IDENTIFIER, "wispr-bro.log");

  // 1. pf + captures.
  let pfToken: string | undefined;
  const caps: ChildProcess[] = [];
  if (mode === "isolated") {
    const ips = await resolveAll(resolvable);
    const rules = anchorRules(user, ips);
    writeFileSync(join(out, "pf.rules"), rules);
    sh("ifconfig", ["pflog0", "create"], true);
    sh("pfctl", ["-a", ANCHOR, "-f", join(out, "pf.rules")]);
    pfToken = sh("pfctl", ["-E"], true).match(/Token\s*:\s*(\d+)/)?.[1];
    caps.push(
      capture(
        ["-n", "-e", "-tttt", "-l", "-i", "pflog0"],
        join(out, "pflog.txt"),
      ),
    );
  } else {
    writeFileSync(join(out, "pflog.txt"), "");
  }
  caps.push(
    capture(
      ["-n", "-l", "-k", "NP", "-i", "pktap,all", "port", "53"],
      join(out, "dns.txt"),
    ),
  );
  await Bun.sleep(2000);

  // 2. launch with a fresh profile (a new user has an empty home).
  // Update checks stay on (Handy's default) so the launch-time check runs;
  // it cannot install anything: the F-02 placeholder feed does not exist.
  const env = [`HOME=${home}`, "WISPRBRO_SELFCHECK=1"];
  const appProc = spawn(
    "sudo",
    ["-u", runAs, "env", ...env, exe, "--start-hidden"],
    {
      stdio: [
        "ignore",
        openSync(join(out, "app.stdout.txt"), "w"),
        openSync(join(out, "app.stderr.txt"), "w"),
      ],
    },
  );
  console.log(
    `launched ${exeName} as ${runAs} (pid ${appProc.pid}); log ${logFile}`,
  );

  // 3. self-check.
  const ready = await waitFor(
    () => logFile,
    /fork selfcheck: (PASS|FAIL)/,
    120_000,
  );
  console.log(
    ready ? "self-check line seen" : "self-check line NOT seen after 120 s",
  );

  // 4. idle.
  console.log(`idling ${idle} s`);
  await Bun.sleep(idle * 1000);

  // 5. stop.
  sh("pkill", ["-TERM", "-u", runAs, "-x", exeName], true);
  await Bun.sleep(3000);
  sh("pkill", ["-KILL", "-u", runAs, "-x", exeName], true);
  for (const c of caps) c.kill("SIGINT");
  await Bun.sleep(1500);
  if (mode === "isolated") {
    sh("pfctl", ["-a", ANCHOR, "-F", "all"], true);
    if (pfToken) sh("pfctl", ["-X", pfToken], true);
  }

  const appLog = existsSync(logFile) ? readFileSync(logFile, "utf8") : "";
  writeFileSync(join(out, "app.log"), appLog);
  const report = analyze({
    pflog: readFileSync(join(out, "pflog.txt"), "utf8"),
    dns: readFileSync(join(out, "dns.txt"), "utf8"),
    appLog,
    allowedHosts: allowed,
    ourProcesses: [exeName, "Wispr Bro", "handy"],
    strictDns: argv.includes("--strict-dns"),
  });
  writeFileSync(join(out, "report.json"), JSON.stringify(report, null, 2));

  console.log(`self-check: ${report.selfcheck} ${report.selfcheckLine ?? ""}`);
  console.log(
    `allowed DNS names queried by the app: ${report.dnsAllowed.join(", ") || "none"}`,
  );
  console.log(
    `update check observed: ${report.updateCheckSeen ? "yes" : "no"}`,
  );
  if (report.dnsUnattributed.length) {
    console.log(
      `unattributed DNS queries (not counted; other processes): ${[...new Set(report.dnsUnattributed.map((q) => q.name))].join(", ")}`,
    );
  }
  for (const b of report.blocked.slice(0, 50)) console.log(`  blocked: ${b}`);
  if (report.failures.length) {
    for (const f of report.failures) console.log(`✗ ${f}`);
    process.exit(1);
  }
  console.log("✓ egress: no traffic outside R5 §1");
}

if (import.meta.main) {
  main().catch((e) => {
    console.error(e);
    process.exit(2);
  });
}
