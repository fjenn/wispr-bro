export type Term = (typeof TERMS)[number];

export interface LocaleGlossary {
  /** How the UI addresses the user, as macOS does in that language. */
  tone: string;
  /** Does macOS ship a UI in this language (so Apple's terms exist)? */
  appleUi: boolean;
  terms: Record<Term, string>;
}

const t = (...values: string[]): Record<Term, string> => {
  if (values.length !== TERMS.length) {
    throw new Error(`glossary row has ${values.length} terms`);
  }
  return Object.fromEntries(
    TERMS.map((term, i) => [term, values[i]]),
  ) as Record<Term, string>;
};

