/** The glossary lines the translation model sees for one locale. */
export function glossaryPrompt(code: string): string[] {
  const entry = GLOSSARY[code];
  if (!entry) return [];
  return [
    `- Tone: ${entry.tone}`,
    "- Use these terms consistently (English → target):",
    ...TERMS.map((term) => `  ${term} → ${entry.terms[term]}`),
  ];
}
