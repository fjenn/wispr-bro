/**
 * Translation glossary and tone per locale (S-37b).
 *
 * One source for two readers: the `llama-server` backend of
 * `wb-translate-missing.ts` puts the locale's entry into its system prompt,
 * and `docs/fork/TRANSLATION-REVIEW.md` prints the same tables for the people
 * who review machine translations (a test keeps the two in step).
 *
 * Terms follow Apple's own macOS wording in that language where macOS has
 * one (Dictation, Settings, Notifications, keyboard shortcut, History); the
 * app's own features (Transform, Scratchpad, snippet, the bar) use the plain
 * word a macOS user of that language would expect. Names stay in English:
 * see `KEEP_AS_IS`.
 */

